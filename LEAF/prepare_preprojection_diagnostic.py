"""Freeze the last-projection representation audit on existing paired training subsets."""
import copy
import json
import time
from pathlib import Path

from d_downstream_qformer_ce import sha256
from prepare_duration_ce_controls import write_new


def main():
    root = Path('runs/paper_merge_v2')
    previous_path = root/'inputs/input_response_v3_design.json'
    previous = json.loads(previous_path.read_text())
    refs, inputs = {}, {str(previous_path): sha256(previous_path)}
    for i in range(2):
        path = root/f'seed0/input_response_v3_shard{i}/run.json'
        run = json.loads(path.read_text())
        assert run['all_model_states_unchanged'] and not run['engineering_smoke']
        inputs[str(path)] = sha256(path)
        refs.update(run['records'])
    assert set(refs) == set(previous['all_tasks'])
    for row in refs.values():
        assert sha256(Path(row['path'])) == row['sha256']
    sources = {name: sha256(Path(name)) for name in previous['source_sha256']}
    for name, digest in previous['source_sha256'].items():
        assert sources[name] == digest
    for name in ['cache_preprojection_representations.py', 'prepare_preprojection_diagnostic.py',
                 'prepare_duration_ce_controls.py']:
        sources[name] = sha256(Path(name))
    for label in ['source_fit', 'coverage_audit']:
        inputs[previous[label]] = sha256(Path(previous[label]))
    motivations = [root/'analysis/teacher_output_compression.json', root/'analysis/binary_antialignment.json']
    inputs.update({str(p): sha256(p) for p in motivations})
    common = {key: copy.deepcopy(previous[key]) for key in ['source_fit', 'coverage_audit', 'models', 'experts', 'batch_size', 'seed']}
    common.update(source_sha256=sources, input_sha256=inputs, reference_records=refs,
                  scope='Frozen teacher/initial/CE/KL native representations on exactly the prior128original plus128replacement training rows per task. Last-projection input2048, raw output768, normalized output768 and native logits only; no layer sweep, new rows, Joint inputs, fitting, validation inference or test access. EEG reads request selected training indices directly; partition labels are read to reconstruct the existing split. Replacement data are dependent training samples and ADHD overlaps. Representation variance/similarity is not proof of useful task knowledge or a causal performance mechanism.')
    design = {**copy.deepcopy(common), 'fixed_unix': time.time(), 'all_tasks': previous['all_tasks'],
              'worker': 'cache_preprojection_representations.py',
              'hypothesis': 'Determine whether final-output class concentration is already present immediately before the final projection, and whether any within-class teacher structure there is missing from CE/KL students. This decides whether an intermediate-representation intervention has a distinct target; it does not establish its usefulness.',
              'primary_analysis': [
                  'All16tasks and both pools, all four models, fixed prehead/raw/unit/centered-logit representations; no best-layer/model/subset selection.',
                  'Class-balanced total/between/within variance grouped by truth and teacher argmax. Each model uses teacher argmax for the second grouping so compared groups remain identical.',
                  'Prehead variance split into the row space and null space of each model own final Linear weight, using FP64 SVD with the standard eps*max(shape)*largest-singular-value rank cutoff. Check orthogonality, energy decomposition and null projection annihilation; keep all ranks and singular-value ranges.',
                  'Teacher-student weighted linear CKA for prehead/raw/unit/centered-logit representations after global centering and after truth-class centering. Weights exactly balance classes within each128pool.',
                  'For class-centered CKA, retain32within-true-class permutations generated by seed[0,task_index,20261117], the same permutations for both pools and all models. Report raw paired CKA, null distribution and paired-minus-null-mean. Permutation calibration is descriptive, not independent semantic or physiological evidence.',
                  'Report KL-minus-CE CKA changes for every task and both pools; task-deletion summaries are sensitivity, not confidence intervals. No threshold chooses a training loss.'
              ],
              'engineering_gate': 'Inline source/model/input hashes, exact selected EEG/label hash replay, native head reconstruction, cached native-logit replay<2e-5 with changed decisions bounded by their margins, all frozen model states exact, no gradients or optimizer. Stop and preserve any failure. The operation is read-only inference, with no separate training smoke.',
              'budget': {'main_forward_examples': 16*256*4, 'optimizer_updates': 0, 'backward_passes': 0},
              'launch_dependency': 'Run only after both duration4800_ce_v2 workers are terminal and the duration comparison has been reported. Do not edit or compete with their live computation.',
              'shards': {str(i): {'tasks': previous['all_tasks'][i::2], 'gpu': i,
                                   'plan': str(root/f'inputs/preprojection_shard{i}_plan.json'),
                                   'outdir': str(root/f'seed0/preprojection_shard{i}'),
                                   'log': str(root/f'seed0/logs/preprojection_shard{i}.log')} for i in range(2)},
              'prior_art': ['https://proceedings.mlr.press/v97/kornblith19a/kornblith19a.pdf',
                            'https://arxiv.org/pdf/1904.05068'],
              'prior_data_read_scope_correction': 'The input_response_v3 worker selected only training rows for all predictions/Jacobians, but its bulk h[key][:] copies for subject-mapped tasks also read unused validation EEG rows from those same subject datasets. Its no-validation-EEG-read scope sentence was too strong. No validation prediction or official-test read occurred in that diagnostic. This new worker reads selected training EEG indices directly, including deduplication of overlapping selected IDs; frozenv3 artifacts are preserved.'}
    design_path = root/'inputs/preprojection_design.json'
    write_new(design_path, design)
    for index, shard in design['shards'].items():
        plan = {**copy.deepcopy(common), 'design': str(design_path), 'design_sha256': sha256(design_path),
                'tasks': shard['tasks'], 'shard': int(index)}
        write_new(Path(shard['plan']), plan)
    print(json.dumps({'design': str(design_path), 'sha256': sha256(design_path), 'budget': design['budget'],
                      'launch_dependency': design['launch_dependency'], 'shards': design['shards']}, indent=2))


if __name__ == '__main__':
    main()
